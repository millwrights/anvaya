const out = [];
const seen = new Set();
const missing = [];
for (const [slug, cat] of CURATED) {
  const ic = bySlug[slug];
  if (!ic) { missing.push(slug); continue; }
  if (seen.has(ic.slug)) continue;
  seen.add(ic.slug);
  out.push({ key: ic.slug, name: ic.title, cat, hex: ic.hex, path: ic.path });
}

