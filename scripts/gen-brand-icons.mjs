  `export interface BrandIcon {\n  key: string;\n  name: string;\n  cat: string;\n  hex: string;\n  path: string;\n}\n\n` +
  `export const BRAND_ICONS: BrandIcon[] = ${JSON.stringify(out)};\n`;

writeFileSync(new URL("../src/document/brand-icons.ts", import.meta.url), file);
