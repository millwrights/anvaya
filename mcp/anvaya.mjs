// Read and write Anvaya `.anvaya` diagram files. A `.anvaya` file is a
// self-contained JSON document (schema/id/title/folder/tags/nodes/edges/
// layouts). We accept a high-level {nodes,edges} spec from the agent and turn it
// into valid native shapes with a layered auto-layout — so the agent never has
// to know Anvaya's internal geometry. Empty per-node `style` lets the app paint
// its vivid theme colors on load.

import { promises as fs, readFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

const ALLOWED_SHAPES = ["rounded", "rect", "ellipse", "diamond", "note", "sticky", "topic"];

// ── icon catalog (generated by scripts/gen-icon-catalog.mjs; mirrors the app) ──
const ICON_CATALOG = (() => {
  try {
    return JSON.parse(readFileSync(new URL("./icons.json", import.meta.url), "utf8"));
  } catch {
    return [];
  }
})();
const ICON_BY_KEY = new Map(ICON_CATALOG.map((i) => [i.key, i]));

// Icon-node geometry — must match src/document/icons.ts (glyph + caption).
const ICON_GLYPH = 72;
const ICON_CAP_W = 132;
const ICON_CAP_LH = 18;
const ICON_CAP_GAP = 6;
function iconNodeSize(label) {
  const t = String(label ?? "").trim();
  if (!t) return [ICON_GLYPH, ICON_GLYPH];
  const perLine = Math.max(6, Math.floor(ICON_CAP_W / 7));
  const lines = Math.min(3, Math.max(1, Math.ceil(t.length / perLine)));
  return [ICON_CAP_W, ICON_GLYPH + lines * ICON_CAP_LH + ICON_CAP_GAP];
}

/** Search the icon library (for the `list_icons` tool). */
export function listIcons({ query, category } = {}) {
  const q = String(query ?? "").trim().toLowerCase();
  const cat = String(category ?? "").trim().toLowerCase();
  let items = ICON_CATALOG;
  if (cat) items = items.filter((i) => i.cat.toLowerCase() === cat);
  if (q)
    items = items.filter(
      (i) =>
        i.key.toLowerCase().includes(q) ||
        i.name.toLowerCase().includes(q) ||
        i.cat.toLowerCase().includes(q),
    );
  return {
    categories: [...new Set(ICON_CATALOG.map((i) => i.cat))],
    total: ICON_CATALOG.length,
    matched: items.length,
    icons: items.slice(0, 200).map((i) => ({ key: i.key, name: i.name, cat: i.cat })),
  };
}

// Size a box to its label so text doesn't overflow. Node has no canvas to
// measure with, so estimate from character counts (the app re-fits precisely on
// edit). Approximates a ~15px sans font with pad=10 like the renderer.
const CHAR_W = 8.0; // avg px per character
const LINE_H = 20; // px per line
const H_PAD = 20; // total horizontal padding
const V_PAD = 22; // total vertical padding
const MIN_W = 110;
const MAX_W = 300;
const MIN_H = 48;

function fitSize(shape, label) {
  if (shape === "sticky") return [168, 168];
  const lines = String(label ?? "").split("\n");
  const longest = Math.max(1, ...lines.map((l) => l.length));
  let w = Math.min(MAX_W, Math.max(MIN_W, Math.round(longest * CHAR_W) + H_PAD));
  const contentW = w - H_PAD;
  let rows = 0;
  for (const l of lines) rows += Math.max(1, Math.ceil((l.length * CHAR_W) / contentW));
  let h = Math.max(MIN_H, rows * LINE_H + V_PAD);
  if (shape === "ellipse") { w = Math.round(w * 1.3); h = Math.round(h * 1.5); }
  if (shape === "diamond") { w = Math.round(w * 1.5); h = Math.round(h * 1.7); }
  return [w, h];
}

export function workspaceRoot() {
  const env = process.env.ANVAYA_WORKSPACE;
  if (env && env.trim()) return env.trim();
  return path.join(os.homedir(), "Documents", "Anvaya");
}

function diagramsDir() {
  return path.join(workspaceRoot(), "diagrams");
}

const rand = (n = 10) => {
  const a = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-";
  let s = "";
  for (let i = 0; i < n; i++) s += a[Math.floor(Math.random() * a.length)];
  return s;
};

const shapeOf = (s) => (ALLOWED_SHAPES.includes(s) ? s : "rounded");

/** Clean an edge-detail spec → {fields,notes} or undefined when empty. */
function normalizeDetail(d) {
  if (!d || typeof d !== "object") return undefined;
  const fields = (Array.isArray(d.fields) ? d.fields : [])
    .map((f) => ({ k: String(f?.k ?? "").slice(0, 60), v: String(f?.v ?? "").slice(0, 400) }))
    .filter((f) => f.k.trim() || f.v.trim());
  const notes = String(d.notes ?? "").slice(0, 4000);
  if (!fields.length && !notes.trim()) return undefined;
  const out = {};
  if (fields.length) out.fields = fields;
  if (notes.trim()) out.notes = notes;
  return out;
}

function slug(s) {
  return (
    (s || "").trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "diagram"
  );
}

// Deterministic serialization (sorted keys, records ordered by id) so files diff
// cleanly — mirrors src/workspace/serialize.ts.
function sortKeys(v) {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v && typeof v === "object") {
    const out = {};
    for (const k of Object.keys(v).sort()) out[k] = sortKeys(v[k]);
    return out;
  }
  return v;
}
function serialize(doc) {
  const normalized = {
    ...doc,
    nodes: [...doc.nodes].sort((a, b) => a.id.localeCompare(b.id)),
    edges: [...doc.edges].sort((a, b) => a.id.localeCompare(b.id)),
    layouts: [...(doc.layouts ?? [])].sort((a, b) => a.id.localeCompare(b.id)),
  };
  return JSON.stringify(sortKeys(normalized), null, 2) + "\n";
}

/** Longest-path layering so a DAG reads as clean top-down layers. */
function layers(ids, edges) {
  const succ = new Map();
  const indeg = new Map();
  ids.forEach((id) => (succ.set(id, []), indeg.set(id, 0)));
  for (const e of edges) {
    if (!succ.has(e.from) || !indeg.has(e.to)) continue;
    succ.get(e.from).push(e.to);
    indeg.set(e.to, indeg.get(e.to) + 1);
  }
  const depth = new Map(ids.map((id) => [id, 0]));
  const left = new Map(indeg);
  const q = ids.filter((id) => left.get(id) === 0);
  while (q.length) {
    const u = q.shift();
    for (const v of succ.get(u)) {
      depth.set(v, Math.max(depth.get(v), depth.get(u) + 1));
      left.set(v, left.get(v) - 1);
      if (left.get(v) === 0) q.push(v);
    }
  }
  return depth;
}

const H_GAP = 100; // gap between boxes in a layer
const V_GAP = 140; // gap between layers (roomy channels for connectors)

const EK = (a, b) => a + "\u0000" + b; // edge key

/**
 * Find back-edges (those pointing to an ancestor) via DFS, so cyclic flowcharts
 * (loops/retries) can be layered as a DAG. Returns a Set of edge keys.
 */
function backEdges(ids, edges) {
  const adj = new Map(ids.map((id) => [id, []]));
  for (const e of edges) if (adj.has(e.from) && adj.has(e.to)) adj.get(e.from).push(e.to);
  const state = new Map(ids.map((id) => [id, 0])); // 0=unseen 1=on-stack 2=done
  const back = new Set();
  const stack = [];
  for (const start of ids) {
    if (state.get(start) !== 0) continue;
    stack.push([start, 0]);
    state.set(start, 1);
    while (stack.length) {
      const frame = stack[stack.length - 1];
      const [u, i] = frame;
      const nbrs = adj.get(u);
      if (i < nbrs.length) {
        frame[1]++;
        const v = nbrs[i];
        const s = state.get(v);
        if (s === 1) back.add(EK(u, v));
        else if (s === 0) {
          state.set(v, 1);
          stack.push([v, 0]);
        }
      } else {
        state.set(u, 2);
        stack.pop();
      }
    }
  }
  return back;
}

/**
 * Layered layout with crossing reduction: assigns each node a center position so
 * children sit under their parents (barycenter ordering), leaving clear vertical
 * channels for connectors. Returns { depth, pos (id->{x,y} centers), bbox }.
 */
function layoutGraph(ids, edges, size) {
  const depth = layers(ids, edges);
  const maxD = Math.max(0, ...ids.map((id) => depth.get(id) ?? 0));
  const layerArr = Array.from({ length: maxD + 1 }, () => []);
  for (const id of ids) layerArr[depth.get(id) ?? 0].push(id);

  const pred = new Map(ids.map((id) => [id, []]));
  const succ = new Map(ids.map((id) => [id, []]));
  for (const e of edges) {
    if (succ.has(e.from) && pred.has(e.to)) {
      succ.get(e.from).push(e.to);
      pred.get(e.to).push(e.from);
    }
  }

  // Barycenter sweeps: order each layer by the mean position of its neighbours
  // in the adjacent layer, so edges shorten and stop crossing over boxes.
  const idx = new Map();
  const reindex = () => layerArr.forEach((layer) => layer.forEach((id, i) => idx.set(id, i)));
  reindex();
  for (let iter = 0; iter < 6; iter++) {
    const down = iter % 2 === 0;
    const order = down ? [...layerArr.keys()] : [...layerArr.keys()].reverse();
    for (const d of order) {
      const neigh = down ? pred : succ;
      const bc = new Map();
      layerArr[d].forEach((id, i) => {
        const vs = neigh.get(id).map((n) => idx.get(n)).filter((v) => v != null);
        bc.set(id, vs.length ? vs.reduce((a, b) => a + b, 0) / vs.length : i);
      });
      layerArr[d].sort((a, b) => bc.get(a) - bc.get(b));
      layerArr[d].forEach((id, i) => idx.set(id, i));
    }
  }

  const rowH = layerArr.map((layer) => Math.max(0, ...layer.map((id) => size(id)[1])));
  const totalH = rowH.reduce((a, b) => a + b, 0) + V_GAP * (layerArr.length - 1);
  const pos = new Map();
  let y = -totalH / 2;
  for (let d = 0; d < layerArr.length; d++) {
    const rowW = layerArr[d].reduce((s, id) => s + size(id)[0], 0) + H_GAP * (layerArr[d].length - 1);
    let x = -rowW / 2;
    for (const id of layerArr[d]) {
      const [w] = size(id);
      pos.set(id, { x: x + w / 2, y: y + rowH[d] / 2 });
      x += w + H_GAP;
    }
    y += rowH[d] + V_GAP;
  }

  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const id of ids) {
    const p = pos.get(id);
    const [w, h] = size(id);
    minX = Math.min(minX, p.x - w / 2);
    maxX = Math.max(maxX, p.x + w / 2);
    minY = Math.min(minY, p.y - h / 2);
    maxY = Math.max(maxY, p.y + h / 2);
  }
  return { depth, pos, bbox: { minX, maxX, minY, maxY } };
}

/**
 * Build node/edge records from a spec, laid out around (originX, originY).
 * Forward edges between adjacent layers auto-route in the channel; back-edges
 * and layer-skipping edges are routed through a clear side gutter so no
 * connector is ever hidden under, or drawn across, another box.
 */
function buildRecords(spec, startZ, originX, originY) {
  const specNodes = spec.nodes ?? [];
  const ids = specNodes.map((n) => n.id);
  const idset = new Set(ids);
  const specEdges = (spec.edges ?? []).filter((e) => idset.has(e.from) && idset.has(e.to));

  const sizeMap = new Map();
  for (const n of specNodes) {
    const ic = n.icon ? ICON_BY_KEY.get(n.icon) : null;
    sizeMap.set(n.id, ic ? iconNodeSize(n.label) : fitSize(shapeOf(n.shape), n.label));
  }
  const size = (id) => sizeMap.get(id);

  // Break cycles so loops layer cleanly; lay out on the forward (DAG) edges.
  const back = backEdges(ids, specEdges);
  const forward = specEdges.filter((e) => !back.has(EK(e.from, e.to)));
  const { depth, pos, bbox } = layoutGraph(ids, forward, size);

  const real = new Map();
  let z = startZ;
  const nodes = specNodes.map((n) => {
    const [w, h] = size(n.id);
    const p = pos.get(n.id);
    const cx = originX + p.x;
    const cy = originY + p.y;
    const id = rand();
    real.set(n.id, id);
    const base = {
      id,
      x: Math.round(cx - w / 2),
      y: Math.round(cy - h / 2),
      w, h,
      text: String(n.label ?? "").slice(0, 200),
      parentId: null, layoutId: null, collapsed: false, z: z++,
    };
    const ic = n.icon ? ICON_BY_KEY.get(n.icon) : null;
    if (ic) {
      // Icon node: a product/tech glyph with the label as caption. Monochrome
      // icons carry their tint; full-color logos keep their own palette.
      return { ...base, shape: "icon", src: ic.svg, style: ic.mono && ic.tint ? { fill: ic.tint } : {} };
    }
    return { ...base, shape: shapeOf(n.shape), style: {} };
  });

  let gutterLane = 0;
  const gutterBase = originX + bbox.maxX + 60; // right of every box
  const edges = specEdges.map((e) => {
    const ds = depth.get(e.from) ?? 0;
    const dt = depth.get(e.to) ?? 0;
    const edge = {
      id: rand(),
      source: real.get(e.from),
      target: real.get(e.to),
      kind: "flow",
      routing: "curved",
      label: e.label ? String(e.label).slice(0, 80) : "",
      style: {},
      arrowStart: false,
      arrowEnd: true,
    };
    // Adjacent forward edge → leave the source's bottom-center and enter the
    // target's top-center (clean vertical flow; these are the vertices on a
    // diamond too). Back-edges and layer-skipping edges go out to a side gutter
    // (staggered), entering/leaving at the right-center, so they clear every box.
    const channel = !back.has(EK(e.from, e.to)) && dt === ds + 1;
    if (channel) {
      edge.sourceAnchor = { fx: 0.5, fy: 1 };
      edge.targetAnchor = { fx: 0.5, fy: 0 };
    } else {
      const laneX = Math.round(gutterBase + gutterLane++ * 46);
      const fy = Math.round(originY + pos.get(e.from).y);
      const ty = Math.round(originY + pos.get(e.to).y);
      edge.routing = "step";
      edge.sourceAnchor = { fx: 1, fy: 0.5 };
      edge.targetAnchor = { fx: 1, fy: 0.5 };
      edge.waypoints = [{ x: laneX, y: fy }, { x: laneX, y: ty }];
    }
    const detail = normalizeDetail(e.detail);
    if (detail) edge.detail = detail;
    return edge;
  });

  return { nodes, edges };
}

async function listFiles() {
  try {
    const names = await fs.readdir(diagramsDir());
    return names.filter((n) => n.endsWith(".anvaya")).sort();
  } catch (e) {
    if (e.code === "ENOENT") return [];
    throw e;
  }
}

async function readDoc(name) {
  const text = await fs.readFile(path.join(diagramsDir(), name), "utf8");
  const doc = JSON.parse(text);
  if (!doc.schema || !String(doc.schema).startsWith("anvaya/diagram@")) {
    throw new Error(`${name} is not an Anvaya diagram file.`);
  }
  return doc;
}

async function writeDoc(name, doc) {
  const dir = diagramsDir();
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(dir, name), serialize(doc), "utf8");
}

async function uniqueName(title) {
  const base = slug(title);
  const existing = new Set(await listFiles());
  let name = base + ".anvaya";
  let i = 1;
  while (existing.has(name)) name = `${base}-${i++}.anvaya`;
  return name;
}

// ── public API ────────────────────────────────────────────────────────────────

export async function listDiagrams() {
  const files = await listFiles();
  const out = [];
  for (const name of files) {
    try {
      const d = await readDoc(name);
      out.push({
        name,
        title: d.title || name.replace(".anvaya", ""),
        folder: d.folder ?? "",
        tags: d.tags ?? [],
        nodes: (d.nodes ?? []).length,
        edges: (d.edges ?? []).length,
      });
    } catch {
      out.push({ name, title: name.replace(".anvaya", ""), folder: "", tags: [], nodes: 0, edges: 0 });
    }
  }
  return out;
}

export async function readDiagram(name) {
  const d = await readDoc(name);
  return {
    name,
    title: d.title,
    folder: d.folder ?? "",
    tags: d.tags ?? [],
    nodes: (d.nodes ?? [])
      .filter((n) => n.shape !== "draw" && n.shape !== "image")
      .map((n) => ({ id: n.id, label: n.text, shape: n.shape })),
    edges: (d.edges ?? []).map((e) => ({
      id: e.id,
      from: e.source,
      to: e.target,
      label: e.label ?? "",
      detail: e.detail,
    })),
  };
}

export async function createDiagram({ title, nodes, edges, folder, tags }) {
  const { nodes: nodeRecs, edges: edgeRecs } = buildRecords({ nodes, edges }, 1, 0, 0);
  const doc = {
    schema: "anvaya/diagram@1",
    id: "diagram",
    title: title || "Untitled",
    folder: folder ?? "",
    tags: tags ?? [],
    nodes: nodeRecs,
    edges: edgeRecs,
    layouts: [],
  };
  const name = await uniqueName(title || "diagram");
  await writeDoc(name, doc);
  return { name, title: doc.title, nodeCount: nodeRecs.length, edgeCount: edgeRecs.length };
}

/** Relabel / reshape one node by id (auto-refits its box, keeping its center). */
export async function updateNode({ name, id, label, shape }) {
  const doc = await readDoc(name);
  const n = (doc.nodes ?? []).find((x) => x.id === id);
  if (!n) throw new Error(`No node "${id}" in ${name}.`);
  if (shape != null && n.shape !== "icon") n.shape = shapeOf(shape);
  if (label != null) n.text = String(label).slice(0, 200);
  const [w, h] = n.shape === "icon" ? iconNodeSize(n.text) : fitSize(n.shape, n.text);
  const cx = n.x + n.w / 2;
  const cy = n.y + n.h / 2;
  n.w = w;
  n.h = h;
  n.x = Math.round(cx - w / 2);
  n.y = Math.round(cy - h / 2);
  await writeDoc(name, doc);
  return { name, id, label: n.text, shape: n.shape };
}

/** Delete a node and any connectors touching it. */
export async function deleteNode({ name, id }) {
  const doc = await readDoc(name);
  const before = (doc.nodes ?? []).length;
  doc.nodes = (doc.nodes ?? []).filter((n) => n.id !== id);
  if (doc.nodes.length === before) throw new Error(`No node "${id}" in ${name}.`);
  const e0 = (doc.edges ?? []).length;
  doc.edges = (doc.edges ?? []).filter((e) => e.source !== id && e.target !== id);
  await writeDoc(name, doc);
  return { name, removedNode: id, removedEdges: e0 - doc.edges.length };
}

/** Set (or clear, with null/"") a node's fill color. */
export async function setNodeColor({ name, id, color }) {
  const doc = await readDoc(name);
  const n = (doc.nodes ?? []).find((x) => x.id === id);
  if (!n) throw new Error(`No node "${id}" in ${name}.`);
  n.style = n.style ?? {};
  if (color) n.style.fill = String(color);
  else delete n.style.fill;
  await writeDoc(name, doc);
  return { name, id, fill: n.style.fill ?? "default" };
}

/** Connect two existing nodes by id (optionally with rich detail). */
export async function addEdge({ name, from, to, label, detail }) {
  const doc = await readDoc(name);
  const ids = new Set((doc.nodes ?? []).map((n) => n.id));
  if (!ids.has(from) || !ids.has(to)) throw new Error(`Both "${from}" and "${to}" must exist.`);
  const edge = {
    id: rand(),
    source: from,
    target: to,
    kind: "flow",
    routing: "curved",
    label: label ? String(label).slice(0, 80) : "",
    style: {},
    arrowStart: false,
    arrowEnd: true,
  };
  const d = normalizeDetail(detail);
  if (d) edge.detail = d;
  doc.edges = doc.edges ?? [];
  doc.edges.push(edge);
  await writeDoc(name, doc);
  return { name, edge: edge.id, from, to };
}

/**
 * Attach (or clear) rich click-to-open detail on an existing connection — the
 * "contract" of the edge: structured fields + freeform notes. Locate the edge by
 * its endpoint node ids (from read_diagram) or directly by its edge id.
 */
export async function annotateEdge({ name, from, to, edgeId, detail }) {
  const doc = await readDoc(name);
  const edges = doc.edges ?? [];
  const edge = edgeId
    ? edges.find((e) => e.id === edgeId)
    : edges.find((e) => e.source === from && e.target === to);
  if (!edge) throw new Error(`No edge ${edgeId || `${from} → ${to}`} in ${name}.`);
  const d = normalizeDetail(detail);
  if (d) edge.detail = d;
  else delete edge.detail;
  await writeDoc(name, doc);
  return { name, edge: edge.id, fields: d?.fields?.length ?? 0, notes: !!d?.notes };
}

/**
 * Inspect a diagram: geometry per node plus computed problems (overlapping
 * boxes). Lets an agent self-correct layout the way a screenshot would, but
 * headless — the app already auto-fits text, so overflow is handled there.
 */
export async function describeDiagram(name) {
  const doc = await readDoc(name);
  const nodes = (doc.nodes ?? []).filter((n) => n.shape !== "draw");
  const boxes = nodes.map((n) => ({ id: n.id, label: n.text, shape: n.shape, x: n.x, y: n.y, w: n.w, h: n.h }));
  const overlaps = [];
  for (let i = 0; i < boxes.length; i++) {
    for (let j = i + 1; j < boxes.length; j++) {
      const a = boxes[i];
      const b = boxes[j];
      if (a.shape === "frame" || b.shape === "frame") continue;
      const ox = Math.max(0, Math.min(a.x + a.w, b.x + b.w) - Math.max(a.x, b.x));
      const oy = Math.max(0, Math.min(a.y + a.h, b.y + b.h) - Math.max(a.y, b.y));
      if (ox > 4 && oy > 4) overlaps.push({ a: a.id, b: b.id, overlapPx: Math.round(ox * oy) });
    }
  }
  return {
    name,
    title: doc.title,
    nodeCount: boxes.length,
    edgeCount: (doc.edges ?? []).length,
    nodes: boxes,
    overlaps,
    ok: overlaps.length === 0,
  };
}

export async function appendToDiagram({ name, nodes, edges }) {
  const doc = await readDoc(name);
  doc.nodes = doc.nodes ?? [];
  doc.edges = doc.edges ?? [];
  doc.layouts = doc.layouts ?? [];

  // Place the new cluster below whatever already exists so it doesn't overlap.
  let maxY = 0;
  let maxZ = 0;
  for (const n of doc.nodes) {
    maxY = Math.max(maxY, (n.y ?? 0) + (n.h ?? 0));
    maxZ = Math.max(maxZ, n.z ?? 0);
  }
  const originY = doc.nodes.length ? maxY + 180 : 0;
  const { nodes: nodeRecs, edges: edgeRecs } = buildRecords({ nodes, edges }, maxZ + 1, 0, originY);
  doc.nodes.push(...nodeRecs);
  doc.edges.push(...edgeRecs);
  await writeDoc(name, doc);
  return { name, added: nodeRecs.length, links: edgeRecs.length };
}
